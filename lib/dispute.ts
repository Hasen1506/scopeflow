import {PdfDocument, wrap, type Font} from './pdf';
import {stamp} from './time';

// Dispute pack: everything needed to prove a project's record outside Scopeflow, in one ZIP. This
// file renders the Bharatiya Sakshya Adhiniyam, 2023 Section 63 certificate as a pre-filled
// template: the record source and the SHA-256 hash of every file in the pack are filled in; the
// person in charge (Part A) and an expert (Part B) complete and sign it. It is not legal advice.

export type PackFile = {name: string; sha256: string; bytes: number; description: string};
export type Section63Model = {
  project_id: string; title: string; client: string; origin: string; generated: string;
  versions: number; decided: number; entries: number; ledger_head: string | null; files: PackFile[];
};

const MARGIN = 48;
export function renderSection63Pdf(m: Section63Model): Uint8Array {
  const doc = new PdfDocument({info: {Title: `Section 63 certificate template: ${m.title}`, Producer: 'Scopeflow'}});
  const W = doc.width - MARGIN * 2;
  let y = 0;
  const page = () => { doc.addPage(); y = doc.height - MARGIN; doc.text(MARGIN, 28, `Scopeflow dispute pack · BSA 2023 s.63 certificate template · project ${m.project_id}`, {size: 7, gray: 0.45}); };
  const need = (h: number) => { if (y - h < 60) page(); };
  const para = (text: string, {size = 9.5, font = 'regular' as Font, gray = 0, gap = 4, indent = 0} = {}) => {
    for (const line of wrap(text, W - indent, size, font)) { need(size + 3); doc.text(MARGIN + indent, y - size, line, {size, font, gray}); y -= size + 3; }
    y -= gap;
  };
  const heading = (text: string) => { need(34); y -= 10; doc.text(MARGIN, y - 9, text.toUpperCase(), {size: 8.5, font: 'bold', gray: 0.3}); y -= 14; doc.line(MARGIN, y, MARGIN + W, y); y -= 8; };
  const blank = (label: string) => para(`${label}: ______________________________________________`, {size: 9.5});

  page();
  doc.text(MARGIN, y - 10, 'CERTIFICATE UNDER SECTION 63(4)(c), BHARATIYA SAKSHYA ADHINIYAM, 2023', {size: 9, font: 'bold', gray: 0.3});
  y -= 28;
  para(m.title, {size: 16, font: 'bold', gap: 2});
  para(`Template generated by Scopeflow on ${stamp(m.generated, 'Asia/Kolkata')} for the records of project ${m.project_id} (client: ${m.client}). The hash values below identify each file in this dispute pack exactly.`, {size: 9.5, gray: 0.3, gap: 8});
  para('This is a pre-filled template, not legal advice. Part A must be completed and signed by the person in charge of the record source; Part B by an expert. Check the current form in the Schedule to the Adhiniyam, and take legal advice, before filing it.', {size: 8.5, gray: 0.4});

  heading('Record source (pre-filled)');
  para(`Source: server / cloud database operated by the Scopeflow service at ${m.origin} (PostgreSQL). Records: ${m.versions} scope version${m.versions === 1 ? '' : 's'}, ${m.decided} with a recorded client decision, and ${m.entries} ledger entr${m.entries === 1 ? 'y' : 'ies'}${m.ledger_head ? `; latest ledger fingerprint ${m.ledger_head}` : ''}.`);
  para('Each decision is fingerprinted with SHA-256 and signed by Scopeflow with Ed25519; ledger entries form a SHA-256 hash chain, each entry signed. chain-proof.json in this pack lets anyone recompute the fingerprints and check the signatures with the public key it contains.');

  heading('Hash values (SHA-256)');
  for (const f of m.files) {
    para(`${f.name} · ${f.bytes} bytes · ${f.description}`, {size: 9, font: 'bold', gap: 0});
    para(f.sha256, {size: 8.5, font: 'mono', gray: 0.2, gap: 4, indent: 10});
  }
  para('Algorithm: SHA-256. The same values are listed in SHA256SUMS.txt in this pack (check with `sha256sum -c SHA256SUMS.txt`).', {size: 8.5, gray: 0.4});

  heading('Part A · to be filled by the party');
  para('I, the undersigned, solemnly affirm and state as follows:');
  blank('Name'); blank('Son / daughter / spouse of'); blank('Residing at / employed at');
  para(`I have produced the electronic records listed above (the files of this Scopeflow dispute pack), taken from the record source described above (server / cloud), which was under my lawful control for regularly creating, storing or processing information for the purposes of my regular activities. During that period the source was working properly, or any period it was not did not affect the electronic records or their accuracy, and the information was regularly fed into it in the ordinary course of those activities. The hash values of the electronic records are those listed above, obtained with SHA-256.`);
  blank('Place'); blank('Date (DD/MM/YYYY) and time (IST)'); blank('Signature');

  heading('Part B · to be filled by the expert');
  para('I, the undersigned expert, state that I have examined the electronic records listed above and their hash values, obtained with SHA-256, and that they match the records produced.');
  blank('Name and designation'); blank('Hash values verified (Yes / No)'); blank('Place'); blank('Date (DD/MM/YYYY) and time (IST)'); blank('Signature');
  return doc.toBytes();
}

/** README for the pack: what each file is and how to check it without Scopeflow. */
export function packReadme(m: Section63Model) {
  return [
    `Scopeflow dispute pack: ${m.title}`,
    `Project ${m.project_id} · client ${m.client} · generated ${m.generated}`,
    '',
    'Files',
    ...m.files.map(f => `  ${f.name.padEnd(36)} ${f.description}`),
    '  section63-certificate.pdf             BSA 2023 s.63 certificate template with these hash values',
    '  SHA256SUMS.txt                        SHA-256 of every file above',
    '',
    'How to check it without Scopeflow',
    '  1. sha256sum -c SHA256SUMS.txt confirms no file was changed after the pack was made.',
    '  2. chain-proof.json: each anchor is SHA-256 of "scopeflow-baseline-v1|project|version|content JSON|signer|decided";',
    '     each ledger entry hash is SHA-256 of "scopeflow-entry-v1|prev_hash|seq|kind|baseline_version|anchor|actor|created|payload_hash".',
    '     Signatures are Ed25519 over "scopeflow-anchor-v1:<anchor>" and "scopeflow-entry-v1:<hash>", with the public key in the file.',
    '  3. Receipts carry a QR code to the public /verify page and, when configured, a PAdES signature that PDF readers check.',
    '  4. timestamps/*.tst are RFC 3161 tokens from an independent authority: openssl ts -verify -digest <hex> -in <file> -token_in -CAfile <authority CA>.',
    '',
    'The Section 63 certificate is a template, not legal advice: complete, sign and check it against the current Schedule before use.',
  ].join('\n') + '\n';
}
